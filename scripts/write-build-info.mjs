#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Stamps the build with where and when it came from.
 *
 * This exists because of a failure that was invisible from inside the code: the
 * extension rejected a field type its own scanner emits, and every schema on
 * disk was correct. The cause was that Chrome had an unpacked extension loaded
 * from a *different folder* — a sibling copy of this repository — whose bundle
 * predated the change. Nothing in the extension could say which folder it came
 * from, so the only symptom was a validator that disagreed with reality.
 *
 * With this, the popup can state the source folder and build time, and the
 * question "is Chrome running the build I just made?" is answered by looking,
 * not by inference.
 */

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'extension', 'src', 'generated');

function git(...args) {
  try {
    return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

const info = {
  builtAt: new Date().toISOString(),
  commit: git('rev-parse', '--short', 'HEAD'),
  branch: git('rev-parse', '--abbrev-ref', 'HEAD'),
  /** The absolute folder this build was produced from. */
  sourceRoot: ROOT,
};

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(
  join(OUT_DIR, 'buildInfo.ts'),
  `/* GENERATED by scripts/write-build-info.mjs — do not edit. */

/**
 * Identifies this build. Rendered in the popup so a stale unpacked extension
 * loaded from another folder is visible rather than merely suspected.
 */
export const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;

export type BuildInfo = typeof BUILD_INFO;
`,
  'utf8',
);

console.log(`Build stamp: ${info.commit} (${info.branch}) from ${info.sourceRoot}`);
